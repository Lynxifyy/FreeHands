/**
 * Discord bot integration for FreeHands automations.
 *
 * The user-facing flow: Automations -> Discord -> a client tool opens a menu
 * that invites the FreeHands bot into a server (OAuth2 bot authorization),
 * then hands the agent the server id so it can build the server over REST.
 *
 * The bot *token* is a secret and never appears in source; it is read from the
 * agent-server secret store under {@link DISCORD_BOT_TOKEN_SECRET_NAME}. Only
 * the bot's public application id — the client id used to build the invite URL
 * — is a constant here.
 */

export const CONNECT_DISCORD_TOOL_NAME = "connect_discord";

/**
 * Action discriminator generated by the SDK for the client-defined Discord
 * tool (`ClientAction_<tool-name>`). Keeps the SDK naming convention contained
 * here instead of repeating its generated class name.
 */
export const CONNECT_DISCORD_ACTION_KIND =
  `ClientAction_${CONNECT_DISCORD_TOOL_NAME}` as const;

/**
 * Prefix of the message the frontend posts back once the user has (or has not)
 * connected the bot. Client tools are acknowledged before the user acts, so
 * this message is the only way to hand the agent the guild id. The chat hides
 * it (see `should-render-event.ts`).
 */
export const DISCORD_CONNECT_RESULT_PREFIX = "[discord-connect] ";

/** Secret the agent reads the bot token from. Never a literal value. */
export const DISCORD_BOT_TOKEN_SECRET_NAME = "DISCORD_BOT_TOKEN";

/**
 * Public application id of the FreeHands Discord bot, used as the OAuth2
 * `client_id` in the invite URL. This is public (Discord exposes it on every
 * invite link); it is the decoded first segment of the bot token.
 */
export const DISCORD_BOT_CLIENT_ID = "1568005572769480704";

export interface DiscordBotPermission {
  /** Discord permission flag name, kept for readability and tests. */
  name: string;
  /** Numeric permission bit. */
  bit: number;
}

/**
 * Permission bits the FreeHands bot asks for so it can *build* a community:
 * create and organise channels, assign roles, post and pin messages, invite
 * people and manage webhooks. Deliberately excludes Administrator and
 * destructive moderation bits.
 */
export const DISCORD_BOT_PERMISSIONS: readonly DiscordBotPermission[] = [
  { name: "ViewChannels", bit: 1 << 10 }, // 1024
  { name: "SendMessages", bit: 1 << 11 }, // 2048
  { name: "ManageMessages", bit: 1 << 13 }, // 8192
  { name: "EmbedLinks", bit: 1 << 14 }, // 16384
  { name: "AttachFiles", bit: 1 << 15 }, // 32768
  { name: "ReadMessageHistory", bit: 1 << 16 }, // 65536
  { name: "AddReactions", bit: 1 << 6 }, // 64
  { name: "UseExternalEmojis", bit: 1 << 18 }, // 262144
  { name: "CreateInstantInvite", bit: 1 << 0 }, // 1
  { name: "ManageChannels", bit: 1 << 4 }, // 16
  { name: "ManageRoles", bit: 1 << 28 }, // 268435456
  { name: "ManageWebhooks", bit: 1 << 29 }, // 536870912
  { name: "ChangeNickname", bit: 1 << 26 }, // 67108864
] as const;

/** Summed permission integer as the string Discord expects in a URL. */
export function discordBotPermissionsValue(): string {
  return String(
    DISCORD_BOT_PERMISSIONS.reduce((total, { bit }) => total + bit, 0),
  );
}

export interface DiscordInviteOptions {
  /** Override the client id (defaults to {@link DISCORD_BOT_CLIENT_ID}). */
  clientId?: string;
  /** Override the permission integer (defaults to the summed bits). */
  permissions?: string;
  /** Pre-select a server so the user only has to approve the bot. */
  guildId?: string;
}

/**
 * OAuth2 bot authorization URL. `scope=bot applications.commands` installs the
 * bot and registers its slash commands; the permissions integer is what the
 * bot is granted at install time.
 */
export function buildDiscordBotInviteUrl(
  options: DiscordInviteOptions = {},
): string {
  const params = new URLSearchParams();
  params.set("client_id", options.clientId ?? DISCORD_BOT_CLIENT_ID);
  params.set("scope", "bot applications.commands");
  params.set(
    "permissions",
    options.permissions ?? discordBotPermissionsValue(),
  );
  if (options.guildId) {
    params.set("guild_id", options.guildId);
    params.set("disable_guild_select", "true");
  }
  return `https://discord.com/oauth2/authorize?${params.toString()}`;
}

/**
 * Deep link that opens the local Discord app. With no path it just focuses the
 * app; pass a route such as `channels/<guild>/<channel>` to open a specific
 * place. `-` is Discord's marker for the current account's default view.
 */
export function discordAppDeepLink(path?: string): string {
  const trimmed = path?.replace(/^\/+/, "");
  return trimmed ? `discord://-/${trimmed}` : "discord://";
}

